// Writes skills/<name>/SKILL.md from skills-src/<name>.md, and skills/SOURCES.json, which pins what they were
// built from. A principle skill (`principle: <slug>` in its source) takes its name, short form and test from
// GovernanceOS's lib/principles/core.ts, "THE single definition of the core", so the website and the Harness
// can't say two things. Run it with the governanceos checkout: `npm run skills -- C:\src\GovernanceOS\governanceos`.
//
// skills/ is committed, like bin/: the plugin runs from a plain checkout, and the version pins the text (C16).
// A skill with no source here (complexity-rubric) is hand-written; it is hashed into SOURCES.json all the same.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parse } from "yaml";

const fail = (message) => {
  console.error(`skills: ${message}`);
  process.exit(1);
};

const governanceos = process.argv[2] ?? process.env.GOVERNANCEOS;
if (!governanceos) fail("give the governanceos checkout: npm run skills -- <path>");
const gov = resolve(governanceos);
const corePath = join(gov, "lib", "principles", "core.ts");
if (!existsSync(corePath)) fail(`${corePath} doesn't exist; is ${gov} the governanceos checkout?`);

// The commit is what SOURCES.json pins, so the sources must be exactly that commit.
const git = (...args) => execFileSync("git", ["-C", gov, ...args], { encoding: "utf8" }).trim();
const dirty = git("status", "--porcelain", "--", "lib/principles", "app/(docs)/manual");
if (dirty) fail(`governanceos has uncommitted changes in the sources:\n${dirty}`);
const commit = git("rev-parse", "HEAD");

const { getCorePrinciple } = await import(pathToFileURL(corePath).href);

const root = resolve(import.meta.dirname, "..");
const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const skills = {};

for (const file of readdirSync(join(root, "skills-src")).filter((f) => f.endsWith(".md")).sort()) {
  const text = readFileSync(join(root, "skills-src", file), "utf8").replace(/\r\n/g, "\n");
  const match = text.match(/^---\n([\s\S]*?)\n---\n+([\s\S]*)$/);
  if (!match) fail(`skills-src/${file} has no frontmatter`);
  const meta = parse(match[1]);
  if (`${meta.name}.md` !== file) fail(`skills-src/${file} is named ${meta.name}`);

  let body = match[2];
  if (meta.principle) {
    const p = getCorePrinciple(meta.principle);
    body = `# ${p.name}\n\n*${p.shortForm}*\n\n**The test:** ${p.test}\n\n${body}`;
  }
  const out = [
    "---",
    `name: ${meta.name}`,
    `description: ${JSON.stringify(meta.description)}`,
    "---",
    "",
    `<!-- Generated by scripts/skills.mjs from skills-src/${file}. Edit that, not this. -->`,
    "",
    body,
  ].join("\n");
  mkdirSync(join(root, "skills", meta.name), { recursive: true });
  writeFileSync(join(root, "skills", meta.name, "SKILL.md"), out);
  skills[meta.name] = { source: `skills-src/${file}`, from: meta.sources ?? [] };
}

for (const name of readdirSync(join(root, "skills")).filter((n) => existsSync(join(root, "skills", n, "SKILL.md"))).sort()) {
  const text = readFileSync(join(root, "skills", name, "SKILL.md"), "utf8");
  skills[name] = { ...(skills[name] ?? { source: "hand-written" }), sha256: sha256(text) };
}

const sources = { governanceos: { repository: "github.com/Sejersen92/GovernanceOS", commit }, skills };
writeFileSync(join(root, "skills", "SOURCES.json"), `${JSON.stringify(sources, null, 2)}\n`);
console.log(`wrote ${Object.keys(skills).length} skills from governanceos ${commit.slice(0, 7)}`);
